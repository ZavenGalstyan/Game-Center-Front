/** seconds between shots for a weapon */
export const shotInterval = (w) => 60 / w.rpm;

/** damage of one projectile at distance d (before hit-zone multiplier) */
export function damageAt(w, d) {
  if (d <= w.r0) return w.dmg;
  if (d >= w.r1) return w.dmgMin;
  return w.dmg + (w.dmgMin - w.dmg) * ((d - w.r0) / (w.r1 - w.r0));
}

/** 0..1 bar values for the loadout screen */
export function statBars(w) {
  const dmg = (w.dmg * w.pellets * 0.6) / 110;
  const dps = (w.dmg * w.pellets * (w.mode === "burst" ? (w.burstN / (w.burstN * (60 / w.rpm) + w.burstGap)) * 60 : w.mode === "bolt" || w.mode === "pump" ? 60 / Math.max(60 / w.rpm, w.cycle) : w.rpm)) / 60;
  return {
    damage: Math.min(1, dmg * 1.1 + 0.05),
    fireRate: Math.min(1, dps / 380),
    range: Math.min(1, (w.r0 + w.r1) / 190),
    accuracy: Math.min(1, Math.max(0.05, 1 - (w.adsSpread * 0.9 + w.recoilV * 0.12 + (w.pellets > 1 ? 0.35 : 0)))),
    mobility: Math.min(1, Math.max(0.05, (w.move - 0.75) / 0.35)),
    handling: Math.min(1, Math.max(0.05, 1 - (w.adsTime - 0.12) / 0.36)),
  };
}
