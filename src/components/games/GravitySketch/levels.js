/* ---------- helpers ---------- */
const box = (x, y, w, h, o = {}) => ({ k: "box", x, y, w, h, s: true, ...o });
const slab = (x1, x2, top, h = 40, o = {}) => box((x1 + x2) / 2, top + h / 2, x2 - x1, h, o);
const ball = (id, x, y, r, c, o = {}) => ({ k: "ball", id, x, y, r, c, ...o });
const domino = (id, x, top, o = {}) => ({ k: "box", id, x, y: top - 60, w: 20, h: 120, c: "teal", d: 0.0007, f: 0.3, ...o });
const rock = (id, x, y) => ({ k: "ball", id, x, y, r: 26, d: 0.004, c: "gray" });
const peg = (x, y, r = 14) => ({ k: "ball", x, y, r, s: true, c: "solid" });
const crate = (id, x, y, s = 60, o = {}) => ({ k: "box", id, x, y, w: s, h: s, c: "orange", crate: true, d: 0.0008, ...o });
const cup = (id, x, y, w = 200, h = 140, o = {}) => ({ k: "cup", id, x, y, w, h, ...o });
const zone = (id, x, y, w, h, o = {}) => ({ k: "zone", id, x, y, w, h, ...o });
const nodraw = (x, y, w, h) => ({ k: "nodraw", x, y, w, h });
const target = (id, x, y, o = {}) => ({ k: "target", id, x, y, ...o });
const sw = (id, x, y, acts, o = {}) => ({ k: "switch", id, x, y, acts, ...o });
const gate = (id, x, y, w, h, o = {}) => ({ k: "gate", id, x, y, w, h, ...o });
const red = (x, y, o = {}) => ball("red", x, y, 34, "red", { face: true, look: "blue", ...o });
const blue = (x, y, o = {}) => ball("blue", x, y, 34, "blue", { face: true, look: "red", ...o });

const CIRCLE = (cx, cy, r, n = 16) => Array.from({ length: n + 1 }, (_, k) => [Math.round(cx + r * Math.cos((k * 2 * Math.PI) / n)), Math.round(cy + r * Math.sin((k * 2 * Math.PI) / n))]);

