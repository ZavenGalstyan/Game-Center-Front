/**
 * Shadow Runner — proves every level with the real sim.
 *
 *   node src/components/games/ShadowRunner/tools/validateLevels.mjs [ids…] [--write] [--quick]
 *
 * Per level:
 *   1. finish            — fastest route exists (BFS over real inputs)
 *   2. all coins         — one run can collect every coin AND finish
 *   3. margin            — still finishable with nerfed physics (jump −4 %,
 *                          climb reach −7 %, NO coyote time, hunter +5 %),
 *                          so nothing needs pixel-perfect play
 *   4. tolerance (info)  — how many jump presses of the fastest route can be
 *                          shifted ±3 sim steps (25 ms) and still finish
 *                          (fastest routes are edge-tight by nature, so this
 *                          is reported, not enforced)
 *   5. structure         — start / checkpoints / finish stand on a surface,
 *                          coins aren't buried in solids, a checkpoint spawn
 *                          isn't inside a laser
 * --write stores par times (all-coins time · 1.12 + 1 s) in levels/par.js.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { LEVELS } from "../levels/index.js";
import { solve, tolerance } from "../engine/bot.js";
import { PHYS } from "../engine/constants.js";

const args = process.argv.slice(2);
const write = args.includes("--write");
const quick = args.includes("--quick");
const ids = args.filter((a) => /^\d+$/.test(a)).map(Number);
const NERF = { jump: 0.96, reach: 0.93, hunter: 1.05, noCoyote: true };

const surfaceAt = (L, x, y) =>
  [...L.solids, ...L.crumbles].some((c) => x >= c.x - 1 && x <= c.x + c.w + 1 && Math.abs(c.y - y) < 1);
const inside = (L, x, y) => L.solids.some((c) => x > c.x + 2 && x < c.x + c.w - 2 && y > c.y + 2 && y < c.y + c.h - 2);

const pars = {};
let failures = 0;
const t0 = Date.now();
for (const L of LEVELS) {
  if (ids.length && !ids.includes(L.id)) continue;
  const errs = [];
  const tl = Date.now();
  if (!surfaceAt(L, L.start.x, L.start.y)) errs.push("start not on a surface");
  if (!surfaceAt(L, L.finish.x, L.finish.y)) errs.push("finish not on a surface");
  for (const c of L.checkpoints) {
    if (!surfaceAt(L, c.x, c.y) && !surfaceAt(L, c.x + PHYS.W, c.y)) errs.push(`checkpoint x=${c.x} not on a surface`);
    if (L.lasers.some((z) => c.x + PHYS.W > z.x && c.x < z.x + z.w && c.y - PHYS.H < z.y + z.h + Math.abs(z.my || 0) && c.y > z.y - Math.abs(z.my || 0)))
      errs.push(`checkpoint x=${c.x} inside a laser`);
  }
  L.coins.forEach((c, i) => inside(L, c.x, c.y) && errs.push(`coin #${i} at ${c.x | 0},${c.y | 0} inside a solid`));

  const fast = solve(L);
  if (!fast.ok) errs.push(`NOT FINISHABLE (got to x=${fast.maxX | 0} of ${L.finish.x})`);
  const all = L.coins.length ? solve(L, { allCoins: true }) : fast;
  if (fast.ok && !all.ok) errs.push(`all ${L.coins.length} coins NOT collectable in one run (best route reached x=${all.maxX | 0})`);
  let nerf = { ok: true };
  if (!quick) {
    nerf = solve(L, { tune: NERF });
    if (fast.ok && !nerf.ok) errs.push(`fails with nerfed physics (x=${nerf.maxX | 0}) — too tight`);
  }
  let tol = { ok: 0, total: 0 };
  if (fast.ok && !quick) {
    tol = tolerance(L, fast.actions, 3);
  }
  const par = all.ok ? Math.ceil((all.time * 1.12 + 1) * 2) / 2 : 999;
  pars[L.id] = par;
  const gap = L.chase ? ` gap≥${Math.round(fast.minGap ?? 0)}` : "";
  const line = `L${String(L.id).padStart(2)} ${L.name.padEnd(22)} len ${String(L.length).padStart(5)} fast ${fast.ok ? fast.time.toFixed(2) : "  -- "}s coins ${all.ok ? `${all.coins}/${L.coins.length}` : `-/${L.coins.length}`} par ${par}${gap} tol ${tol.ok}/${tol.total} (${((Date.now() - tl) / 1000).toFixed(1)}s)`;
  console.log((errs.length ? "FAIL " : "ok   ") + line);
  for (const e of errs) console.log("       - " + e);
  if (errs.length) failures++;
}
console.log(`\n${failures ? `${failures} level(s) FAILED` : "all levels passed"} in ${((Date.now() - t0) / 1000).toFixed(0)}s`);

if (write) {
  const here = dirname(fileURLToPath(import.meta.url));
  const file = join(here, "..", "levels", "par.js");
  let prev = {};
  try {
    prev = (await import("../levels/par.js")).default;
  } catch {
    /* first write */
  }
  const merged = { ...prev, ...pars };
  const body = Object.keys(merged)
    .sort((a, b) => a - b)
    .map((k) => `  ${k}: ${merged[k]},`)
    .join("\n");
  writeFileSync(file, `/** Par times (s) — generated by tools/validateLevels.mjs --write. Do not edit by hand. */\nexport default {\n${body}\n};\n`);
  console.log("wrote", file);
}
process.exit(failures ? 1 : 0);
