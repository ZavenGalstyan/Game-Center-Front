/**
 * Jump Ball — handcrafted levels (pure data; no components per level).
 *
 * Coordinates are world units, y-UP, `y` = platform TOP surface. Playfield is
 * 600 wide with hard walls. The first platform is the start pad, the last is
 * the goal. Every level is proven completable (and all 3 stars collectable)
 * by tools/validateLevels.mjs, which drives the REAL sim with a steering bot
 * whose control authority is reduced per world — that reduction is the
 * safety margin.
 *
 * Physics reference (engine/constants.js): apex ≈ 250 u, spring apex ≈ 520 u,
 * max air travel on a flat jump ≈ 340 u.
 *
 * Helpers:
 *   n(x, y, w)                  normal
 *   mv(x, y, w, amp, period, phase?, axis?)   moving
 *   br(x, y, w)                 breaking
 *   sp(x, y, w)                 spring
 *   vn(x, y, w, cycle?)         vanishing
 *   ic(x, y, w)                 ice
 *   kx(x, y, w)                 spikes (hazard)
 *   mic(...) / mvn(...)         moving ice / moving vanishing
 */
const n = (x, y, w) => ({ type: "normal", x, y, w });
const mv = (x, y, w, amp, period, phase = 0, axis = "x") => ({ type: "moving", x, y, w, move: { axis, amp, period, phase } });
const br = (x, y, w) => ({ type: "breaking", x, y, w });
const sp = (x, y, w = 100) => ({ type: "spring", x, y, w });
const vn = (x, y, w, cycle = {}) => ({ type: "vanish", x, y, w, cycle });
const ic = (x, y, w) => ({ type: "ice", x, y, w });
const kx = (x, y, w, h = 24) => ({ type: "spikes", x, y, w, h });
const mic = (x, y, w, amp, period, phase = 0) => ({ type: "ice", x, y, w, move: { axis: "x", amp, period, phase } });
const mvn = (x, y, w, amp, period, phase = 0, cycle = {}) => ({ type: "vanish", x, y, w, cycle, move: { axis: "x", amp, period, phase } });

function level(id, world, name, targetTime, start, rows, goal, stars) {
  const platforms = [{ ...start, type: "start" }, ...rows, { ...goal, type: "finish" }].map((p, i) => ({ id: `L${id}p${i}`, ...p }));
  return { id, world, name, width: 600, targetTime, platforms, stars: stars.map(([x, y]) => ({ x, y })) };
}

