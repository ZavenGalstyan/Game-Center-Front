const mirror = (row) => row + [...row.slice(0, -1)].reverse().join("");

/** Per-level tuning: enemy speed and power time rise/fall with the level. */
export const LEVELS = HALVES.map((half, i) => ({
  rows: half.map(mirror),
  hue: [190, 285, 150, 330, 210, 40, 120, 260, 0, 300][i],
  enemySpeed: 4.3 + i * 0.27, // tiles / s (player: 5.6 + i * 0.1)
  playerSpeed: 5.6 + i * 0.1,
  power: Math.max(2.4, 7 - i * 0.5), // seconds
  release: Math.max(0.45, 1 - i * 0.06), // multiplier on home release times
  bonus: [100, 200, 300, 500, 700, 1000, 1500, 2000, 3000, 5000][i],
}));
