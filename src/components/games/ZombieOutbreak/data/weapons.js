export function getWeapon(id) {
  return WEAPONS[id] || WEAPONS.pistol;
}

/** 0..1 ratings for the Weapon Select bars (derived, so they never drift from the data). */
export function weaponRatings(w) {
  const dps = (w.damage * w.pellets * w.rpm) / 60;
  return {
    damage: Math.min(1, (w.damage * w.pellets + (w.splash ? w.splash.damage * 0.5 : 0)) / 140),
    fireRate: Math.min(1, w.rpm / 800),
    accuracy: Math.max(0.05, Math.min(1, 1 - w.spread / 0.085)),
    capacity: Math.min(1, w.mag / 32),
    dps: Math.round(dps),
  };
}
