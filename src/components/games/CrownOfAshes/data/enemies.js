/** Base XP for a kill scales with the enemy's level against yours. */
export function killXp(def, enemyLevel, playerLevel) {
  const diff = enemyLevel - playerLevel;
  return Math.max(2, Math.round(def.xp * (1 + Math.max(-0.7, Math.min(0.6, diff * 0.15)))));
}
