/**
 * The 20 levels of the Abyss Facility. Every level is data: an ASCII map
 * (tile legend in engine/sim.js), entities (doors, levers, terminals,
 * generators, valves, gauges, crates, pads, reflectors, items, mutants…),
 * puzzle locks, valve sequences, pipe boards, clue texts and two progressive
 * hints. tools/routes.mjs holds a scripted solution for each level that
 * tools/levelTest.mjs replays through the real simulation (with a combat bot),
 * so none can silently become unsolvable.
 *
 * Map: # wall · . floor · S start · K checkpoint · X exit (lift / hatch /
 * submarine) · ~ flooded (swim, oxygen drains) · w deep water with air above
 * · , shallow water · ^ sparking cables · = low platform (jump onto it) · r
 * collapsed debris · T lab desk · | laser grid / steam (see legend) · m toxic
 * leak · o support column · G glass partition · P specimen tank · O ocean
 * window. Wall devices name the wall they hang on with `dir`.
 */
