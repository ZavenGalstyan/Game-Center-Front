export function finalize(raw) {
  const world = WORLDS[Math.max(0, Math.ceil(raw.id / 10) - 1)];
  const platforms = raw.platforms.map((p, i) => ({ id: `p${i}`, surface: "wood", ...p }));
  const xs0 = Math.min(...platforms.map((p) => p.x));
  const xs1 = Math.max(...platforms.map((p) => p.x + p.w + (p.move?.axis === "x" ? p.move.range : 0)));
  const topMax = Math.max(...platforms.map((p) => p.top + (p.move?.axis === "y" ? p.move.range : 0)));
  return {
    world: world.id,
    theme: world.theme,
    view: 170,
    wind: 0,
    collectibles: [],
    props: [],
    difficulty: { tolerance: 16 },
    par: 3,
    ...raw,
    platforms,
    bounds: {
      x0: xs0 - 45,
      x1: xs1 + 55,
      y0: -30,
      y1: Math.max(260, topMax + 120),
      ...(raw.bounds || {}),
    },
  };
}

