/**
 * Level generator (offline):  node src/components/games/NeonCircuit/tools/generate.mjs
 * Deterministic (seeded). Each spec [n, optimum, count] draws random press
 * sets on an all-OFF board and keeps boards whose GF(2) optimum is exactly
 * that many moves, at least 3 lights ON, and new up to rotation/reflection.
 * Tiers are ordered by optimal moves (solution complexity), mixing grid sizes.
 * Writes ../levels.js as [n, board bitmask, optimal moves, tier].
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as E from "../engine.js";

const SPECS = {
  easy: [[3, 2, 3], [3, 3, 4], [4, 3, 3], [3, 4, 4], [4, 4, 4], [3, 5, 4], [5, 4, 3], [4, 5, 5]],
  medium: [[3, 6, 3], [5, 5, 4], [4, 6, 5], [3, 7, 3], [5, 6, 5], [4, 7, 5], [3, 8, 2], [5, 7, 5], [5, 8, 3]],
  hard: [[3, 9, 1], [5, 8, 3], [5, 9, 5], [5, 10, 6], [5, 11, 6], [5, 12, 6], [5, 13, 5], [5, 14, 2], [5, 15, 1]],
};
const rand = E.rng(20261022);
const seen = new Set(), out = [];
for (const [tier, specs] of Object.entries(SPECS))
  for (const [n, m, count] of specs) {
    let got = 0;
    for (let t = 0; got < count && t < 2e6; t++) {
      const set = Math.floor(rand() * 2 ** (n * n));
      const board = E.apply(n, set);
      if (E.minMoves(n, board) !== m || E.lit(board) < 3) continue;
      const key = `${n}:${E.canonical(n, board)}`;
      if (seen.has(key)) continue;
      seen.add(key);
      out.push([n, board, m, tier]);
      got++;
    }
    if (got < count) throw new Error(`only ${got}/${count} boards for ${n}x${n} m=${m}`);
  }
if (out.length !== 100) throw new Error(`expected 100 levels, got ${out.length}`);
const body = out.map((l) => `  ${JSON.stringify(l)},`).join("\n");
writeFileSync(
  fileURLToPath(new URL("../levels.js", import.meta.url)),
  `/** Neon Circuit levels — generated by tools/generate.mjs, validated by
 *  tools/engineTest.mjs. [grid size, board bitmask (bit r*n+c = ON), optimal moves, tier] */
export const LEVELS = [
${body}
];
`,
);
console.log("wrote", out.length, "levels");
