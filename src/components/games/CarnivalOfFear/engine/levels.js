/**
 * Carnival of Fear: Clown Hunt — the ten levels.
 *
 * Maps are ASCII grids of 2 m cells (see CELL in sim.js):
 *   #  wall / tent canvas / mirror        =  railing (blocks movement, not sight or shots)
 *   .  floor                              D  door (E opens; clowns can force it)
 *   1-4 gates (opened by objectives)       X  exit gate
 *   P  player start     R  "reach" marker (in order of the reach steps)
 *   c  creepy clown     j  fast jester     a  armored clown     K  the Clown King
 *   p  pistol ammo      s  shotgun shells  e  blaster energy cells   h  medkit
 *   G  pistol (level 1) S  shotgun         B  Carnival Blaster  f  fuse (collect steps)
 *   w  wall lever       F  fortune machine (E: one free gift)   z  wave spawn point
 *   T  scripted scare trigger (in reading order → level.scares)
 *   *  neon lamp        !  red warning light   ^  sparking electric floor (hazard)
 *   A  arcade cabinet   b  crates / barrels    t  table / counter   Y  prize stall
 *   n  circus drum / pedestal                  O  centre of the level's big prop, o = its footprint
 *
 * Each level is a list of objective steps; finishing a step can open gates.
 * The final step is always "exit", which unlocks the exit gate.
 */

