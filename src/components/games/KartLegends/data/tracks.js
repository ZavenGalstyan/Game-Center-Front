/**
 * Kart Legends — the 30 tracks (5 cups × 6). Each is a closed loop of
 * control points (metres, racing direction = point order; the finish line
 * sits at the first point heading to the second), plus:
 *
 *   width      road half-width            margin   off-road band to the barrier
 *   pads       boost pads: fraction of the lap, or [fraction, lateral offset]
 *   pickups    boost-gem rows (fractions)
 *   shortcut   { fromXY, toXY (mouths, nearest track point), via: [[x, z]…],
 *              kind, width } — two shapes are used: a straight cut across a
 *              hairpin (big saving, two sharp turns) or the base of a bulge
 *              in a straight (small saving, rough or narrow)
 *   narrow     [[from, to, halfWidth]]   slippery  [[from, to]] (ice)
 *   hills      elevation amplitude (m)   landmark  a set piece for the scenery
 *   scale      uniform scale of all coordinates
 *   difficulty 0–1 rival strength
 *
 * Every track is validated (engine/track.js validateTrack) and raced to the
 * finish by the test driver in tools/simTest.mjs.
 */

/** Mirror a layout left↔right (turn directions flip; data stays readable). */
function mirror(t) {
  const m = ([x, z]) => [-x, z];
  return {
    ...t,
    pts: t.pts.map(m),
    shortcut: t.shortcut && { ...t.shortcut, fromXY: m(t.shortcut.fromXY), toXY: m(t.shortcut.toXY), via: t.shortcut.via.map(m) },
  };
}

