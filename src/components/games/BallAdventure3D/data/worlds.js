export function getWorld(id) {
  return WORLDS.find((w) => w.id === id) || null;
}

export function getWorldForLevel(levelId) {
  return WORLDS.find((w) => levelId >= w.levelStart && levelId <= w.levelEnd) || null;
}

export function worldUnlocked(world, totalStars) {
  return world.built && totalStars >= world.unlockStars;
}
