/**
 * Game translation pipeline.
 *
 *   node scripts/i18n/build.mjs            rebuild src/i18n/games/*.json + gameCatalogIds.js
 *   node scripts/i18n/build.mjs todo DIR   write untranslated strings to DIR/todo-NNN.txt
 *                                          ("id<TAB>English", in game order)
 *   node scripts/i18n/build.mjs merge DIR  read DIR/done-NNN.txt ("id<TAB>Russian") back
 *                                          into the translation memory, then rebuild
 *
 * The translation memory (scripts/i18n/games.ru.json, English -> Russian) is
 * shared by every game, so a string translated once covers every game that
 * uses it. Per-game catalogs are split out so the app only downloads the
 * catalog of the game being played. Run the plain build after adding a game
 * or editing game text; anything without a translation simply stays English.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { extractStrings } from "./extract.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../..");
const GAMES = path.join(ROOT, "src/components/games");
const OUT = path.join(ROOT, "src/i18n/games");
const TM_FILE = path.join(HERE, "games.ru.json");
// Strings only seen at runtime (composed from data the extractor can't follow):
// { "Folder": ["string", ...] }, added to that game's extracted strings.
const EXTRA_FILE = path.join(HERE, "extra-strings.json");
// Per-game wording, over the shared memory: a code typed on a Latin keypad stays
// English here though other games translate the word, and logos split into two
// words swap them for Russian word order: { "Folder": { "BLADE": "РЫВОК" } }.
const OVERRIDES_FILE = path.join(HERE, "game-overrides.ru.json");
const TODO_CHUNK = 900;
const COMMON_MIN_GAMES = 4;
const COMMON_WORDS = JSON.parse(fs.readFileSync(path.join(HERE, "common-words.ru.json"), "utf8"));
// Templates every game may compose ("{0} of {1}"), and game titles, which games
// also quote inside other text ("Blade Rush play area").
const COMMON_PATTERNS = JSON.parse(fs.readFileSync(path.join(HERE, "common-patterns.ru.json"), "utf8"));
const GAME_INFO = JSON.parse(fs.readFileSync(path.join(ROOT, "src/i18n/locales/gameInfo.ru.json"), "utf8"));

const readJson = (f, fallback) => (fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : fallback);
const sortedObject = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));

function sourceFiles(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory() && e.name !== "tools") sourceFiles(path.join(dir, e.name), acc);
    else if (/\.jsx?$/.test(e.name)) acc.push(path.join(dir, e.name));
  }
  return acc;
}

/** Text drawn on a canvas that is kept (a texture or cached sprite) can't follow a language switch. */
function bakesText(folder) {
  const code = sourceFiles(path.join(GAMES, folder)).map((f) => fs.readFileSync(f, "utf8")).join("\n");
  return /\.(fill|stroke)Text\(/.test(code) && /CanvasTexture|OffscreenCanvas|createElement\(["']canvas["']\)/.test(code);
}

function gameStrings(folder, extra) {
  const { exact, templates } = extractStrings(path.join(GAMES, folder));
  const more = extra[folder] || [];
  return {
    exact: [...new Set([...exact, ...more.filter((s) => !/\{\d+\}/.test(s))])].sort(),
    templates: [...new Set([...templates, ...more.filter((s) => /\{\d+\}/.test(s))])].sort(),
  };
}

function gameFolders() {
  return fs
    .readdirSync(GAMES, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

/** registry.js: "Game Name": Component, Component = lazy(() => import("./Folder/...")) */
function buildCatalogIds() {
  const src = fs.readFileSync(path.join(GAMES, "registry.js"), "utf8");
  const folderOf = {};
  for (const m of src.matchAll(/(?:const|import)\s+(\w+)\s*(?:=\s*lazy\(\s*\(\)\s*=>\s*import\(\s*|from\s*)["']\.\/([^/"']+)\//g)) {
    folderOf[m[1]] = m[2];
  }
  const block = src.slice(src.indexOf("const GAME_COMPONENTS"), src.indexOf("};", src.indexOf("const GAME_COMPONENTS")));
  const ids = {};
  for (const m of block.matchAll(/^\s*("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|\w+)\s*:\s*(\w+)\s*,?\s*$/gm)) {
    const name = m[1].replace(/^["']|["']$/g, "").replace(/\\(.)/g, "$1");
    if (folderOf[m[2]]) ids[name.trim().replace(/\s+/g, " ").toLowerCase()] = folderOf[m[2]];
  }
  const body = JSON.stringify(sortedObject(ids), null, 2);
  const baked = JSON.stringify([...new Set(Object.values(ids))].filter(bakesText).sort(), null, 2);
  fs.writeFileSync(
    path.join(ROOT, "src/i18n/gameCatalogIds.js"),
    `// Generated by scripts/i18n/build.mjs from games/registry.js — do not edit.\n` +
      `// Normalized game name -> game folder (= catalog file in ./games/).\n` +
      `export const GAME_CATALOG_IDS = ${body};\n\n` +
      `// Folders of the games that keep text baked into textures or cached sprites.\n` +
      `export const BAKED_TEXT_GAMES = ${baked};\n`,
  );
  return Object.keys(ids).length;
}

function build() {
  const tm = readJson(TM_FILE, {});
  const extra = readJson(EXTRA_FILE, {});
  const overrides = readJson(OVERRIDES_FILE, {});
  fs.mkdirSync(OUT, { recursive: true });
  let total = 0;
  let covered = 0;
  const usedBy = new Map(); // string -> number of games using it
  for (const folder of gameFolders()) {
    const { exact, templates } = gameStrings(folder, extra);
    for (const s of exact) usedBy.set(s, (usedBy.get(s) || 0) + 1);
    const e = {};
    const p = {};
    for (const s of exact) {
      if (!tm[s]) continue;
      // Listed even when unchanged, so no fallback picks words out of it.
      e[s] = tm[s];
      // "fail:Time ran out" style keys: the game shows the part after the tag.
      const m = /^[a-z]+:(.+)$/.exec(s);
      const r = /^[a-z]+:(.+)$/.exec(tm[s]);
      if (m && r) e[m[1]] = r[1];
    }
    for (const s of templates) if (tm[s]) p[s] = tm[s];
    Object.assign(e, overrides[folder]);
    total += exact.length + templates.length;
    covered += exact.filter((s) => tm[s]).length + templates.filter((s) => tm[s]).length;
    const file = path.join(OUT, `${folder}.json`);
    if (Object.keys(e).length + Object.keys(p).length === 0) {
      if (fs.existsSync(file)) fs.unlinkSync(file);
      continue;
    }
    fs.writeFileSync(file, JSON.stringify({ e: sortedObject(e), p: sortedObject(p) }) + "\n");
  }
  // _common: short UI strings shared by many games, plus hand-listed words
  // (COMMON_WORDS) that games keep as lowercase keys and show through CSS
  // text-transform ("medium" -> "Medium"). Loaded under every game catalog.
  const common = {};
  for (const [s, n] of usedBy) if (n >= COMMON_MIN_GAMES && s.length <= 40 && tm[s] && tm[s] !== s) common[s] = tm[s];
  for (const [en, ru] of Object.entries(COMMON_WORDS)) common[en] ??= ru;
  for (const [en, { name }] of Object.entries(GAME_INFO)) {
    common[en] ??= name;
    common[en.split(":")[0]] ??= name.split(":")[0];
  }
  fs.writeFileSync(path.join(OUT, "_common.json"), JSON.stringify({ e: sortedObject(common), p: sortedObject(COMMON_PATTERNS) }) + "\n");
  const games = buildCatalogIds();
  console.log(`catalogs built: ${covered}/${total} strings translated, ${games} registry names mapped`);
}

function todo(dir) {
  const tm = readJson(TM_FILE, {});
  const extra = readJson(EXTRA_FILE, {});
  fs.mkdirSync(dir, { recursive: true });
  for (const f of fs.readdirSync(dir)) if (/^todo-\d+\.txt$/.test(f)) fs.unlinkSync(path.join(dir, f));
  const seen = new Set(Object.keys(tm));
  const list = [];
  for (const folder of gameFolders()) {
    const { exact, templates } = gameStrings(folder, extra);
    for (const s of [...exact, ...templates]) {
      if (seen.has(s) || s.includes("\t") || s.includes("\n")) continue;
      seen.add(s);
      list.push({ s, folder });
    }
  }
  let chunk = 0;
  for (let i = 0; i < list.length; i += TODO_CHUNK) {
    let last = null;
    const lines = [];
    list.slice(i, i + TODO_CHUNK).forEach(({ s, folder }, j) => {
      if (folder !== last) lines.push(`## ${folder}`);
      last = folder;
      lines.push(`${i + j}\t${s}`);
    });
    fs.writeFileSync(path.join(dir, `todo-${String(chunk++).padStart(3, "0")}.txt`), lines.join("\n") + "\n");
  }
  fs.writeFileSync(path.join(dir, "todo-index.json"), JSON.stringify(list.map((x) => x.s)));
  console.log(`${list.length} untranslated strings in ${chunk} chunks -> ${dir}`);
}

function merge(dir) {
  const tm = readJson(TM_FILE, {});
  const index = readJson(path.join(dir, "todo-index.json"), null);
  if (!index) throw new Error("run `todo` first");
  let added = 0;
  for (const f of fs.readdirSync(dir).filter((n) => /^done-\d+\.txt$/.test(n)).sort()) {
    // Ids of the matching todo chunk that the translator left out on purpose
    // (proper names, debug text) are recorded as "keep English".
    const todoFile = path.join(dir, f.replace("done-", "todo-"));
    if (fs.existsSync(todoFile)) {
      for (const line of fs.readFileSync(todoFile, "utf8").split(/\r?\n/)) {
        const m = /^(\d+)\t/.exec(line);
        const en = m && index[Number(m[1])];
        if (en !== undefined && en !== null && !(en in tm)) tm[en] = en;
      }
    }
    for (const line of fs.readFileSync(path.join(dir, f), "utf8").split(/\r?\n/)) {
      const m = /^(\d+)\t(.*)$/.exec(line);
      if (!m) continue;
      const en = index[Number(m[1])];
      const ru = m[2].trim();
      if (en === undefined || !ru) continue;
      // keep slot markers honest: a translation must use the same {n} set
      const slots = (x) => (x.match(/\{\d+\}/g) || []).sort().join();
      if (slots(en) !== slots(ru)) {
        console.warn(`slot mismatch, skipped: ${m[1]}  ${en}  =>  ${ru}`);
        continue;
      }
      tm[en] = ru === "=" ? en : ru;
      added++;
    }
  }
  // one entry per line keeps the memory diff-friendly
  const lines = Object.entries(sortedObject(tm)).map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`);
  fs.writeFileSync(TM_FILE, `{\n${lines.join(",\n")}\n}\n`);
  console.log(`merged ${added} translations (memory now ${Object.keys(tm).length})`);
  build();
}

const [cmd, dir] = process.argv.slice(2);
if (cmd === "todo") todo(path.resolve(dir));
else if (cmd === "merge") merge(path.resolve(dir));
else build();
